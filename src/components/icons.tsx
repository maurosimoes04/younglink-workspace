export function PageIcon({ name, fallback = "file-text", className = "h-4 w-4" }: { name?: string | null; fallback?: string; className?: string }) {
  const Cmp = (name && PAGE_ICONS[name]) || PAGE_ICONS[fallback] || FileText;
  return <Cmp className={`shrink-0 ${className}`} strokeWidth={1.75} aria-hidden />;
}

export const hasPageIcon = (name?: string | null) => !!name && name in PAGE_ICONS;
